"""Produce a native Linux binary package; source export is explicitly opt-in."""
import argparse
import gzip
import hashlib
import io
import importlib.util
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tarfile
import tempfile

ROOT = Path(__file__).resolve().parents[1]
FILES = (
    "Cargo.toml", "Cargo.lock", "CMakeLists.txt", "LICENSE", "install.sh", "build.sh",
    "core-rust/Cargo.toml", "core-rust/LICENSE", "core-rust/config.example.toml",
    "packaging/install.py", "packaging/build.py", "packaging/native.py", "packaging/cross.py", "packaging/viet-config.desktop",
    "packaging/Dockerfile.deb", "packaging/Dockerfile.rpm", ".dockerignore",
    "wrappers/ibus-c/engine.c", "wrappers/ibus-c/CMakeLists.txt", "wrappers/ibus-c/viet.xml.in",
    "wrappers/fcitx5-cpp/engine.cpp", "wrappers/fcitx5-cpp/CMakeLists.txt",
    "wrappers/fcitx5-cpp/viet.conf", "wrappers/fcitx5-cpp/viet-addon.conf",
)
SOURCE_DIRS = {"core-rust/src": {".rs", ".json"}, "core-rust/include": {".h"}}
MARKER = ".viet-ime-disk.json"
ARCHIVE = "viet-ime-linux-source.tar.gz"
LINUX_README = """# Viet IME — bản nguồn sạch để cài Linux

Trong thư mục này chạy:

    sh install.sh

Xem trước, không thay đổi hệ thống:

    sh install.sh --dry-run

Chọn rõ framework nếu cần:

    sh install.sh --framework ibus
    sh install.sh --framework fcitx5

Tự nhận diện framework và dependency trên Debian/Ubuntu, Fedora, Arch,
openSUSE và Alpine. Cần Internet, SDK framework tương thích, Rust >= 1.85;
bộ cài hỗ trợ cài dependency và dùng sudo/doas khi chép vào hệ thống.
Đăng xuất/đăng nhập, thêm Viet IME trong Input Sources/Input Method.
Mở Viet IME Settings hoặc chạy viet-config --gui để cấu hình chung.

Đây là bộ mã nguồn: Linux sẽ biên dịch theo libc, kiến trúc và framework
của máy đích. Không kèm binary Windows hoặc binary Linux đã biên dịch.
NixOS/Guix, distro immutable và framework Flatpak cần đóng gói riêng.

Tạo gói theo máy Linux đang build:

    sh install.sh --package deb
    sh install.sh --package rpm

Không kèm test, cache, cấu hình cá nhân hay mã nguồn upstream tham chiếu.
FILES.sha256 liệt kê checksum các tệp phát hành. Giấy phép: LICENSE.
"""

def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()

def without_tests(text):
    lines = []
    skip = False
    for line in text.splitlines(keepends=True):
        if line.strip().startswith("["):
            skip = line.strip() == "[[test]]"
        if not skip:
            lines.append(line)
    return "".join(lines).rstrip() + "\n"

def tree_files(root):
    result = {}
    for path in sorted(root.rglob("*")):
        if path.is_symlink():
            raise RuntimeError("Refusing symlink in generated output: " + str(path))
        if path.is_file() and path.name != MARKER:
            result[path.relative_to(root).as_posix()] = digest(path)
    return result

def check_owned_output(output):
    if output.is_symlink():
        raise RuntimeError("disk must not be a symlink")
    if not output.exists():
        return
    if output.is_dir() and not any(output.iterdir()):
        return
    marker = output / MARKER
    if not marker.is_file() or marker.is_symlink():
        raise RuntimeError("Existing disk/ is not generated by this tool; move it before exporting")
    data = json.loads(marker.read_text(encoding="utf-8"))
    if data.get("format") not in ("viet-ime-disk-v1", "viet-ime-binary-v1") or data.get("files") != tree_files(output):
        raise RuntimeError("disk/ contains changed or unmanaged files; move it before exporting")

def remove_work_tree(path, work):
    # Resolve and bound every recursive deletion to the dedicated build workspace.
    resolved = path.resolve()
    if path.is_symlink() or resolved == work.resolve():
        raise RuntimeError("Unsafe work-tree cleanup")
    try:
        resolved.relative_to(work.resolve())
    except ValueError:
        raise RuntimeError("Cleanup escaped the build workspace")
    if resolved.exists():
        shutil.rmtree(resolved)

def publish(staging, root, work, kind):
    output = root / "disk"
    check_owned_output(output)
    manifest = {"format": kind, "files": tree_files(staging)}
    (staging / MARKER).write_text(json.dumps(manifest, sort_keys=True), encoding="utf-8")
    backup = None
    if output.exists():
        backup = work / ("previous-" + staging.name)
        os.replace(output, backup)
    try:
        os.replace(staging, output)
    except OSError:
        if backup is not None:
            os.replace(backup, output)
        raise
    if backup is not None:
        remove_work_tree(backup, work)
    return output

def export(root=ROOT):
    root = root.resolve()
    output = root / "disk"
    check_owned_output(output)
    work = root / "target/disk-build"
    if work.is_symlink() or (root / "target").is_symlink():
        raise RuntimeError("Export staging must stay inside the project")
    work.mkdir(parents=True, exist_ok=True)
    staging = Path(tempfile.mkdtemp(prefix="stage-", dir=work))
    try:
        kit = staging / "viet-ime"
        kit.mkdir()
        sources = list(FILES)
        for directory, extensions in SOURCE_DIRS.items():
            for path in sorted((root / directory).rglob("*")):
                if path.is_symlink():
                    raise RuntimeError("Refusing symlink in sources: " + str(path))
                if path.is_file() and path.suffix in extensions:
                    sources.append(path.relative_to(root).as_posix())
        for name in sorted(sources):
            source = root / name
            if source.is_symlink() or not source.is_file():
                raise RuntimeError("Missing or unsafe source: " + name)
            # Every exported file is UTF-8 text, normalized for Linux even on Windows.
            content = source.read_text(encoding="utf-8-sig").replace("\r\n", "\n")
            if name == "core-rust/Cargo.toml":
                content = without_tests(content)
            destination = kit / name
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_bytes(content.encode("utf-8"))
            destination.chmod(0o755 if destination.suffix == ".sh" else 0o644)
        (kit / "README.md").write_bytes(LINUX_README.encode("utf-8"))
        checksums = "".join(value + "  " + name + "\n" for name, value in tree_files(kit).items())
        (kit / "FILES.sha256").write_bytes(checksums.encode("utf-8"))
        archive = staging / ARCHIVE
        with archive.open("wb") as raw, gzip.GzipFile(filename="", mode="wb", fileobj=raw, mtime=0) as compressed:
            with tarfile.open(fileobj=compressed, mode="w", format=tarfile.PAX_FORMAT) as tar:
                for path in [kit] + sorted(kit.rglob("*")):
                    info = tarfile.TarInfo(path.relative_to(staging).as_posix())
                    info.mode = 0o755 if path.is_dir() or path.suffix == ".sh" else 0o644
                    if path.is_dir():
                        info.type = tarfile.DIRTYPE
                        tar.addfile(info)
                    else:
                        content = path.read_bytes()
                        info.size = len(content)
                        tar.addfile(info, io.BytesIO(content))
        (staging / "SHA256SUMS").write_bytes((digest(archive) + "  " + ARCHIVE + "\n").encode("ascii"))
        return publish(staging, root, work, "viet-ime-disk-v1")
    finally:
        if staging.exists():
            remove_work_tree(staging, work)

def main(argv=None):
    parser = argparse.ArgumentParser(description="Build a precompiled Linux installer into disk/ (DEB by default).")
    parser.add_argument("--format", choices=["deb", "rpm", "tar"], default="deb")
    parser.add_argument("--framework", choices=["both", "ibus", "fcitx5"], default="both")
    parser.add_argument("--builder", choices=["auto", "cross", "native", "docker", "podman"], default="auto")
    parser.add_argument("--platform", choices=["linux/amd64", "linux/arm64"], default="linux/amd64")
    parser.add_argument("--from-build", type=Path, help="Package an already configured native CMake build")
    parser.add_argument("--skip-tests", action="store_true")
    parser.add_argument("--output", type=Path, help=argparse.SUPPRESS)
    parser.add_argument("--source", action="store_true", help="Export a source kit instead of a binary installer")
    parser.add_argument("--skip-build", action="store_true", help="With --source, export without building the library")
    args = parser.parse_args(argv)
    if not args.source:
        if args.skip_build: parser.error("--skip-build is only valid with --source; binary packages must be compiled")
        use_cross=args.builder=="cross" or (args.builder=="auto" and sys.platform!="linux")
        spec = importlib.util.spec_from_file_location("viet_native", ROOT / ("packaging/cross.py" if use_cross else "packaging/native.py"))
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        return module.run(args, ROOT, publish)
    if not args.skip_build:
        subprocess.run(["cargo", "build", "--release", "--locked", "--lib"], cwd=ROOT, check=True)
    output = export()
    print("Clean Linux source kit: " + str(output / "viet-ime"))
    print("Archive: " + str(output / ARCHIVE))
    return 0

if __name__ == "__main__":
    try:
        sys.exit(main())
    except (OSError, RuntimeError, ValueError, subprocess.CalledProcessError) as error:
        print("viet-ime build: " + str(error), file=sys.stderr)
        sys.exit(1)
